!> The generated pages of the manual's keyword documentation (ROADMAP D47, D85, D104), written
!> from the keyword table (cfg_table_mod) and the option-compatibility rules (cfg_rules_mod):
!>   - per implemented keyword, the facts and notes of its entry
!>     (doc/generated/keywords/<name>.inc): the values (kind, range or allowed words,
!>     form), the unit, the default, where it is given (run-wide or in a phase block), and a
!>     note with every rule that concerns it, in both directions. The manual's narrative pages
!>     document each keyword in a "confval" entry of its own and include this file in it;
!>   - the keyword reference (doc/keywords_table.rst): one row per implemented keyword,
!>     linked to its entry (planned keywords are not documented, D104);
!>   - the compatibility table (doc/compatibility_table.rst): one row per rule.
!> The program fepx_keywords writes them; the docs tests check that the committed copies are
!> current.
!>
!> Source : FEPX (ROADMAP step 9.9, D104; the reference since task M.1, D47). Contains no
!>          numerical method.
!>
!> Public routines:
!>   cfg_manual_keyword    write the facts and notes of one keyword's entry
!>   cfg_manual_reference  write the keyword reference
!>   cfg_manual_rules      write the compatibility table
!>   cfg_manual_values     the values of a keyword, as written in its entry
module cfg_manual_mod

  use kinds_mod, only: rk, ik
  use cfg_table_mod, only: cfg_keyword_t, cfg_keywords, cfg_active, cfg_phase, cfg_single, &
    & cfg_per_step, cfg_comp_per_step, cfg_repeat, cfg_flag, cfg_list, cfg_int, cfg_real, &
    & cfg_word
  use cfg_rules_mod, only: cfg_rules, cfg_rule_sentence, cfg_rule_involves
  use crystal_mod, only: crystal_num_families, crystal_family_token, crystal_family_size, &
    & crystal_default_families, crystal_structure_name

  implicit none

  private

  public :: cfg_manual_keyword, cfg_manual_reference, cfg_manual_rules, cfg_manual_values
  public :: per_family_names, saturation_names

  !> The keywords given per slip family or per slip system (step 6.1, D48), and those given so
  !> with saturation_anisotropic only (step 6.2, D49): their values are documented as such
  !> (config_mod checks the counts; test_cfg_manual checks that they are list keywords).
  character(len=*), parameter :: per_family_names = 'm gammadot_0 tau_0'
  character(len=*), parameter :: saturation_names = 'h_0 tau_s n'

  !> The number of crystal structures (codes 1 to 4 of crystal_mod).
  integer, parameter :: num_structures = 4

contains

  !> Write the facts and notes of one keyword's entry: a field list (Values, Unit, Default,
  !> Given) and, if rules concern the keyword, a note listing them (one bullet per rule).
  !>
  !> Arguments:
  !>   unit  (in)  integer  output unit
  !>   i     (in)  integer  keyword-table index (an implemented keyword)
  !> Locals:
  !>   k        type(cfg_keyword_t)  the entry
  !>   i_rule   integer              rule index
  !>   n_rules  integer              number of rules that concern the keyword
  subroutine cfg_manual_keyword(unit, i)

    integer, intent(in) :: unit, i

    type(cfg_keyword_t) :: k
    integer :: i_rule, n_rules

    k = cfg_keywords(i)

    ! Header comment: the file is generated, not edited by hand.
    write (unit, '(a)') '.. Generated by fepx_keywords from src/io/cfg_table_mod.f90 and ' // &
      & 'src/io/cfg_rules_mod.f90.'
    write (unit, '(a)') '   Do not edit: change the tables in the source and regenerate.'
    write (unit, '(a)') ''

    ! The facts (the slip families: the families of every crystal type, from crystal_mod).
    write (unit, '(a)') ':Values: ' // cfg_manual_values(k)
    if (k%name == 'slip_families') call write_families(unit)
    if (len_trim(k%unit) > 0 .and. k%unit /= '-') write (unit, '(a)') ':Unit: ' // trim(k%unit)
    if (k%name == 'slip_families') then
      write (unit, '(a)') ':Default: ' // default_families_rst()
    else if (len_trim(k%default_text) > 0) then
      write (unit, '(a)') ':Default: ' // default_rst(trim(k%default_text))
    end if
    if (k%scope == cfg_phase) then
      write (unit, '(a)') ':Given: in each phase block (``phase``)'
    else
      write (unit, '(a)') ':Given: once, for the whole run'
    end if

    ! The rules that concern the keyword, as one note.
    n_rules = 0
    do i_rule = 1, size(cfg_rules)
      if (cfg_rule_involves(i_rule, trim(k%name))) n_rules = n_rules + 1
    end do
    if (n_rules == 0) return
    write (unit, '(a)') ''
    write (unit, '(a)') '.. note::'
    write (unit, '(a)') ''
    do i_rule = 1, size(cfg_rules)
      if (.not. cfg_rule_involves(i_rule, trim(k%name))) cycle
      if (n_rules == 1) then
        write (unit, '(a)') '   ' // cfg_rule_sentence(i_rule)
      else
        write (unit, '(a)') '   - ' // cfg_rule_sentence(i_rule)
      end if
    end do

  end subroutine cfg_manual_keyword

  !> Write the keyword reference: one list-table row per implemented keyword, in table order
  !> (keyword linked to its entry, values, unit, default, description).
  !>
  !> Arguments:
  !>   unit  (in)  integer  output unit
  !> Locals:
  !>   i     integer              table index
  !>   k     type(cfg_keyword_t)  the entry
  subroutine cfg_manual_reference(unit)

    integer, intent(in) :: unit

    integer :: i
    type(cfg_keyword_t) :: k

    ! Header comment and the table's directive.
    write (unit, '(a)') '.. Generated by fepx_keywords from src/io/cfg_table_mod.f90.'
    write (unit, '(a)') '   Do not edit: change the table in the source and regenerate.'
    write (unit, '(a)') ''
    write (unit, '(a)') '.. list-table::'
    write (unit, '(a)') '   :header-rows: 1'
    write (unit, '(a)') '   :widths: 22 30 8 14 26'
    write (unit, '(a)') '   :class: fepx-wrap'
    write (unit, '(a)') ''
    write (unit, '(a)') '   * - Keyword'
    write (unit, '(a)') '     - Values'
    write (unit, '(a)') '     - Unit'
    write (unit, '(a)') '     - Default'
    write (unit, '(a)') '     - Description'

    ! The rows.
    do i = 1, size(cfg_keywords)
      k = cfg_keywords(i)
      if (k%status /= cfg_active) cycle
      call cell(unit, ':confval:`' // trim(k%name) // '`', .true.)
      call cell(unit, cfg_manual_values(k), .false.)
      if (k%unit == '-') then
        call cell(unit, '', .false.)
      else
        call cell(unit, trim(k%unit), .false.)
      end if
      call cell(unit, default_rst(trim(k%default_text)), .false.)
      call cell(unit, trim(k%info), .false.)
    end do

  end subroutine cfg_manual_reference

  !> Write the compatibility table: one list-table row per rule (the keywords concerned, linked
  !> to their entries, and the rule's sentence).
  !>
  !> Arguments:
  !>   unit  (in)  integer  output unit
  !> Locals:
  !>   i_rule  integer                    rule index
  !>   links   character(:), allocatable  the keywords as links
  subroutine cfg_manual_rules(unit)

    integer, intent(in) :: unit

    integer :: i_rule
    character(len=:), allocatable :: links

    ! Header comment and the table's directive.
    write (unit, '(a)') '.. Generated by fepx_keywords from src/io/cfg_rules_mod.f90.'
    write (unit, '(a)') '   Do not edit: change the table in the source and regenerate.'
    write (unit, '(a)') ''
    write (unit, '(a)') '.. list-table::'
    write (unit, '(a)') '   :header-rows: 1'
    write (unit, '(a)') '   :widths: 30 70'
    write (unit, '(a)') '   :class: fepx-wrap'
    write (unit, '(a)') ''
    write (unit, '(a)') '   * - Keywords'
    write (unit, '(a)') '     - Rule'

    ! The rows: the subjects, then the condition keywords not among them.
    do i_rule = 1, size(cfg_rules)
      links = confval_links(trim(cfg_rules(i_rule)%subjects), '')
      links = links // confval_links(trim(cfg_rules(i_rule)%condition_keywords), &
        & trim(cfg_rules(i_rule)%subjects))
      call cell(unit, links, .true.)
      call cell(unit, cfg_rule_sentence(i_rule), .false.)
    end do

  end subroutine cfg_manual_rules

  !> The values of a keyword, as written in its entry and in the reference: the table's
  !> values_text when given; the slip families; the per-family parameters; otherwise the kind
  !> (integer, real, one of the allowed words as literals, text), the range, and the form (one
  !> per step, a component first, a repeatable line, no value, one or more values).
  !>
  !> Arguments:
  !>   k  (in)  type(cfg_keyword_t)  the entry (an implemented keyword)
  !> Locals:
  !>   kind_text  character(:), allocatable  the kind and range
  function cfg_manual_values(k) result(text)

    type(cfg_keyword_t), intent(in) :: k
    character(len=:), allocatable :: text

    character(len=:), allocatable :: kind_text

    ! Values described by the table, the slip families, and the per-family parameters.
    if (len_trim(k%values_text) > 0) then
      text = trim(k%values_text)
      return
    end if
    if (k%name == 'slip_families') then
      text = '``all``, or one or more slip families of the crystal type, each once, written ' // &
        & 'exactly as listed (:ref:`slip_systems`); their order numbers the slip systems'
      return
    end if
    if (in_names(per_family_names, k%name)) then
      text = 'real' // range_rst(k) // ': one value per active slip family, in the order ' // &
        & 'of ``slip_families`` (or of the default families), or one value per slip system, ' // &
        & 'in the slip-system order'
      return
    end if
    if (in_names(saturation_names, k%name)) then
      text = 'real' // range_rst(k) // ': one value; with ``hardening ' // &
        & 'saturation_anisotropic`` also one value per active slip family, in the order of ' // &
        & '``slip_families`` (or of the default families), or one value per slip system'
      return
    end if

    ! The kind, with its range or its words.
    select case (k%kind)
    case (cfg_int)
      kind_text = 'integer' // range_rst(k)
    case (cfg_real)
      kind_text = 'real' // range_rst(k)
    case (cfg_word)
      kind_text = 'one of ' // word_list(trim(k%words))
    case default
      kind_text = 'text'
    end select

    ! The form.
    select case (k%form)
    case (cfg_per_step)
      text = kind_text // ', one value per step'
    case (cfg_comp_per_step)
      text = 'a component, then ' // kind_text // ', one value per step'
    case (cfg_repeat)
      text = kind_text // '; the line may be repeated'
    case (cfg_flag)
      text = 'none (the keyword alone)'
    case (cfg_list)
      text = kind_text // ', one or more values'
    case default
      text = kind_text
    end select
    if (k%step_dash) text = text // ' (``-`` for a step without a value)'

  end function cfg_manual_values

  !> Write the slip families of every crystal type, as a bullet list continuing the Values field:
  !> "``fcc``: ``{111}<110>`` (12 systems)", ...
  !>
  !> Arguments:
  !>   unit  (in)  integer  output unit
  !> Locals:
  !>   structure  integer                    crystal structure code
  !>   family     integer                    family index
  !>   line       character(:), allocatable  the line of a structure
  !>   count      character(12)              number of systems as text
  subroutine write_families(unit)

    integer, intent(in) :: unit

    integer :: structure, family
    character(len=:), allocatable :: line
    character(len=12) :: count

    write (unit, '(a)') ''
    do structure = 1, num_structures
      line = '   - ``' // crystal_structure_name(structure) // '``: '
      do family = 1, crystal_num_families(structure)
        write (count, '(i0)') crystal_family_size(structure, family)
        if (family > 1) line = line // ', '
        line = line // '``' // crystal_family_token(structure, family) // '`` (' // &
          & trim(count) // ' systems)'
      end do
      write (unit, '(a)') line
    end do
    write (unit, '(a)') ''

  end subroutine write_families

  !> The default slip families of every crystal type (crystal_mod): "all families" or the
  !> default families' tokens.
  !>
  !> Locals:
  !>   structure  integer               crystal structure code
  !>   families   integer(:), allocatable  the default families of a structure
  !>   i          integer               family index
  function default_families_rst() result(text)

    character(len=:), allocatable :: text

    integer :: structure, i
    integer, allocatable :: families(:)

    text = ''
    do structure = 1, num_structures
      families = crystal_default_families(structure)
      if (structure > 1) text = text // '; '
      text = text // '``' // crystal_structure_name(structure) // '``: '
      if (size(families) == crystal_num_families(structure)) then
        text = text // 'all families'
      else
        do i = 1, size(families)
          if (i > 1) text = text // ', '
          text = text // '``' // crystal_family_token(structure, families(i)) // '``'
        end do
      end if
    end do

  end function default_families_rst

  !> Whether a keyword is in a blank-separated list of names.
  !>
  !> Arguments:
  !>   names  (in)  character  the names
  !>   name   (in)  character  the keyword
  pure function in_names(names, name) result(found)

    character(len=*), intent(in) :: names, name
    logical :: found

    found = index(' ' // names // ' ', ' ' // trim(name) // ' ') > 0

  end function in_names

  !> The range of a numeric keyword: " > 0", " >= 1", " from 0 to 1", " > 0 and <= 1", " <= 1",
  !> or nothing.
  !>
  !> Arguments:
  !>   k  (in)  type(cfg_keyword_t)  the entry
  !> Locals:
  !>   has_lo, has_hi  logical  bounded below, above
  function range_rst(k) result(text)

    type(cfg_keyword_t), intent(in) :: k
    character(len=:), allocatable :: text

    logical :: has_lo, has_hi

    has_lo = k%lo > -huge(1.0_rk)
    has_hi = k%hi < huge(1.0_rk)
    if (has_lo .and. has_hi .and. .not. k%lo_open) then
      text = ' from ' // number_text(k%lo) // ' to ' // number_text(k%hi)
    else if (has_lo .and. has_hi) then
      text = ' > ' // number_text(k%lo) // ' and <= ' // number_text(k%hi)
    else if (has_lo .and. k%lo_open) then
      text = ' > ' // number_text(k%lo)
    else if (has_lo) then
      text = ' >= ' // number_text(k%lo)
    else if (has_hi) then
      text = ' <= ' // number_text(k%hi)
    else
      text = ''
    end if

  end function range_rst

  !> Short text of a range bound: an integer when the value is whole, else g0.
  !>
  !> Arguments:
  !>   x  (in)  real(rk)  the bound
  !> Locals:
  !>   buffer  character(32)  formatted value
  function number_text(x) result(text)

    real(rk), intent(in) :: x
    character(len=:), allocatable :: text

    character(len=32) :: buffer

    if (abs(x) < 1.0e15_rk .and. .not. abs(x - aint(x)) > 0.0_rk) then
      write (buffer, '(i0)') nint(x, ik)
    else
      write (buffer, '(g0)') x
    end if
    text = trim(adjustl(buffer))

  end function number_text

  !> A default as written in an entry: a value as a literal; "required", "required (<when>)"
  !> and descriptions (e.g. "per crystal_type") as plain text.
  !>
  !> Arguments:
  !>   default_text  (in)  character  the table's default
  function default_rst(default_text) result(text)

    character(len=*), intent(in) :: default_text
    character(len=:), allocatable :: text

    if (len(default_text) == 0) then
      text = ''
    else if (index(default_text, 'required') == 1 .or. index(default_text, ' ') > 0) then
      text = default_text
    else
      text = '``' // default_text // '``'
    end if

  end function default_rst

  !> A blank-separated list of words as literals separated by commas: "``a``, ``b``, ``c``".
  !>
  !> Arguments:
  !>   words  (in)  character  the words, separated by blanks
  !> Locals:
  !>   rest   character(:), allocatable  the words not yet written
  !>   blank  integer                    position of the next blank in rest
  function word_list(words) result(list)

    character(len=*), intent(in) :: words
    character(len=:), allocatable :: list

    character(len=:), allocatable :: rest
    integer :: blank

    list = ''
    rest = trim(adjustl(words))
    do while (len(rest) > 0)
      ! The next word, and the rest.
      blank = index(rest, ' ')
      if (blank == 0) blank = len(rest) + 1
      if (len(list) > 0) list = list // ', '
      list = list // '``' // rest(1:blank - 1) // '``'
      if (blank > len(rest)) then
        rest = ''
      else
        rest = trim(adjustl(rest(blank + 1:)))
      end if
    end do

  end function word_list

  !> Blank-separated keywords as confval links separated by commas, leaving out those in a list
  !> of exclusions, each preceded by a comma when the result continues a list.
  !>
  !> Arguments:
  !>   words     (in)  character  the keywords, separated by blanks
  !>   excluded  (in)  character  keywords to leave out, separated by blanks
  !> Locals:
  !>   rest   character(:), allocatable  the keywords not yet written
  !>   word   character(:), allocatable  the current keyword
  !>   blank  integer                    position of the next blank in rest
  function confval_links(words, excluded) result(list)

    character(len=*), intent(in) :: words, excluded
    character(len=:), allocatable :: list

    character(len=:), allocatable :: rest, word
    integer :: blank

    list = ''
    rest = trim(adjustl(words))
    do while (len(rest) > 0)
      ! The next keyword, and the rest.
      blank = index(rest, ' ')
      if (blank == 0) blank = len(rest) + 1
      word = rest(1:blank - 1)
      if (blank > len(rest)) then
        rest = ''
      else
        rest = trim(adjustl(rest(blank + 1:)))
      end if
      ! Written unless excluded; a comma before every keyword of a continued list.
      if (index(' ' // excluded // ' ', ' ' // word // ' ') > 0) cycle
      if (len(list) > 0 .or. len(excluded) > 0) list = list // ', '
      list = list // ':confval:`' // word // '`'
    end do

  end function confval_links

  !> Write one list-table cell: "   * - text" for the first cell of a row, "     - text"
  !> otherwise; an empty cell is written as a bare "-".
  !>
  !> Arguments:
  !>   unit   (in)  integer    output unit
  !>   text   (in)  character  cell text
  !>   first  (in)  logical    first cell of a row
  !> Locals:
  !>   lead   character(:), allocatable  the line start
  subroutine cell(unit, text, first)

    integer, intent(in) :: unit
    character(len=*), intent(in) :: text
    logical, intent(in) :: first

    character(len=:), allocatable :: lead

    ! Row start or continuation.
    if (first) then
      lead = '   * -'
    else
      lead = '     -'
    end if

    ! Cell text after one blank, or nothing for an empty cell.
    if (len_trim(text) == 0) then
      write (unit, '(a)') lead
    else
      write (unit, '(a)') lead // ' ' // trim(text)
    end if

  end subroutine cell

end module cfg_manual_mod
