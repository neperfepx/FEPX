!> FEPX slip-system reference generator: writes the slip systems of every crystal type (number
!> in the default order, family token, Miller or Miller-Bravais label), from crystal_mod's
!> tables, as reStructuredText: the slip-system lists of the manual
!> (doc/slip_systems_table.rst).
!>
!> Usage: fepx_slip_systems <file>   write the lists to <file> (replaced if it exists)
!>
!> Source : FEPX (ROADMAP step 6.1). Contains no numerical method. Serial (no MPI).
!>
!> Locals:
!>   path       character(1024)  output file name (first command argument)
!>   unit, ios  integer          output unit, I/O status of the open
!>   structure  integer          crystal structure code
!>   family     integer          canonical family
!>   system     integer          full-table system index
!>   k          integer          system within its family
!>   name       character(:), allocatable  structure name
program fepx_slip_systems

  use error_mod, only: fatal_error
  use crystal_mod, only: crystal_structure_name, crystal_num_families, crystal_family_token, &
    & crystal_family_size, crystal_system_label

  implicit none

  character(len=1024) :: path
  integer :: unit, ios, structure, family, system, k
  character(len=:), allocatable :: name

  ! Exactly one argument: the output file.
  if (command_argument_count() /= 1) call fatal_error('fepx_slip_systems', &
    & 'usage: fepx_slip_systems <output file>')
  call get_command_argument(1, path)
  open (newunit=unit, file=trim(path), status='replace', action='write', iostat=ios)
  if (ios /= 0) call fatal_error('fepx_slip_systems', 'cannot open ' // trim(path))

  ! Header comment: the file is generated, not edited by hand.
  write (unit, '(a)') '.. Generated by fepx_slip_systems from src/material/crystal_mod.f90.'
  write (unit, '(a)') '   Do not edit: change the tables in the source and regenerate.'

  ! One table per structure; the full table is family after family in canonical order.
  do structure = 1, 4
    name = crystal_structure_name(structure)
    write (unit, '(a)') ''
    write (unit, '(a)') '.. list-table:: ``' // name // '``'
    write (unit, '(a)') '   :header-rows: 1'
    write (unit, '(a)') '   :widths: 10 40 50'
    write (unit, '(a)') ''
    write (unit, '(a)') '   * - System'
    write (unit, '(a)') '     - Family'
    write (unit, '(a)') '     - (plane)[direction]'
    system = 0
    do family = 1, crystal_num_families(structure)
      do k = 1, crystal_family_size(structure, family)
        system = system + 1
        write (unit, '(a,i0)') '   * - ', system
        write (unit, '(a)') '     - ``' // crystal_family_token(structure, family) // '``'
        write (unit, '(a)') '     - ``' // crystal_system_label(structure, system) // '``'
      end do
    end do
  end do
  close (unit)

end program fepx_slip_systems
