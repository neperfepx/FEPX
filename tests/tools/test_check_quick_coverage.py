"""Unit tests of dev/tools/check_quick_coverage.py (ROADMAP step 9.6, D88).

Each test checks one parsing or file-mapping function on small synthetic inputs (keyword table,
configuration file, gcov output, a build tree of empty gcov files). The functions that run gcov
and ctest are exercised by the coverage job of dev/tools/ci_local.sh. Run directly or through CTest
(test tools_check_quick_coverage).
"""

import os
import sys
import tempfile
import unittest

# Import check_quick_coverage from dev/tools/ (two levels up from this file, then dev/tools).
TOOLS_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "dev", "tools")
sys.path.insert(0, os.path.normpath(TOOLS_DIR))
import check_quick_coverage  # noqa: E402

# A keyword reference in the form fepx_keywords writes: three implemented keywords (two
# enumerated, one with the form after the values).
KEYWORD_TABLE = """.. Generated by fepx_keywords from src/io/cfg_table_mod.f90.

.. list-table::
   :header-rows: 1
   :class: fepx-wrap

   * - Keyword
     - Values
     - Unit
     - Default
     - Description
   * - :confval:`number_of_phases`
     - integer >= 1
     -
     - required
     - number of phases
   * - :confval:`restart`
     - one of ``on``, ``off``
     -
     - ``off``
     - continue simulation.sim
   * - :confval:`print`
     - one of ``coo``, ``stress``; the line may be repeated
     -
     -
     - output variable
"""

# gcov -n output for an object whose source includes another file.
GCOV_OUTPUT = """File '/src/material/included_table.inc'
Lines executed:0.00% of 4
File '/src/material/yield_vertices_mod.f90'
Lines executed:96.20% of 79
"""


class CheckQuickCoverageTest(unittest.TestCase):
    """Tests of the parsing and file-mapping functions."""

    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = self.temp.name

    def tearDown(self):
        self.temp.cleanup()

    def touch(self, *parts):
        """Create an empty file root/<parts>, with its directories; return its path."""
        path = os.path.join(self.root, *parts)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="ascii"):
            pass
        return path

    def test_keyword_table_reads_every_keyword_row(self):
        keywords = check_quick_coverage.parse_keyword_table(KEYWORD_TABLE)
        self.assertEqual(list(keywords), ["number_of_phases", "restart", "print"])

    def test_keyword_table_enumerated_values_without_remarks(self):
        keywords = check_quick_coverage.parse_keyword_table(KEYWORD_TABLE)
        self.assertEqual(keywords["number_of_phases"][0], [])
        self.assertEqual(keywords["print"][0], ["coo", "stress"])

    def test_keyword_table_defaults_and_empty_cells(self):
        keywords = check_quick_coverage.parse_keyword_table(KEYWORD_TABLE)
        self.assertEqual(keywords["restart"], (["on", "off"], "off"))
        self.assertEqual(keywords["print"][1], "")
        self.assertEqual(keywords["number_of_phases"][1], "required")

    def test_cfg_lines_skip_comments_and_blank_lines(self):
        path = os.path.join(self.root, "simulation.cfg")
        with open(path, "w", encoding="ascii") as handle:
            handle.write("## Section\nnumber_of_phases 1\n\n  print coo  # a remark\n")
        self.assertEqual(check_quick_coverage.cfg_lines(path),
                         [("number_of_phases", ["1"]), ("print", ["coo"])])

    def test_gcov_summary_of_the_named_source(self):
        executed, total = check_quick_coverage.parse_gcov_summary(GCOV_OUTPUT,
                                                                  "yield_vertices_mod.f90")
        self.assertEqual((executed, total), (76, 79))

    def test_gcov_summary_without_executable_lines(self):
        self.assertEqual(check_quick_coverage.parse_gcov_summary("No executable lines\n",
                                                                 "kinds_mod.f90"), (0, 0))

    def test_notes_files_map_objects_to_sources(self):
        source = os.path.join(self.root, "source")
        build = os.path.join(self.root, "build")
        self.touch("source", "src", "math", "tensor_mod.f90")
        self.touch("source", "src", "app", "fepx.f90")
        tensor = self.touch("build", "CMakeFiles", "fepx_core.dir", "math",
                            "tensor_mod.f90.gcno")
        program = self.touch("build", "CMakeFiles", "fepx.dir", "app", "fepx.f90.gcno")
        # Counter files and the notes of sources outside src/ are not mapped.
        self.touch("build", "CMakeFiles", "fepx_core.dir", "math", "tensor_mod.f90.gcda")
        self.touch("build", "CMakeFiles", "fepx_core.dir", "math", "gone_mod.f90.gcno")
        notes = check_quick_coverage.notes_files(build, source)
        self.assertEqual(notes, {os.path.join("src", "math", "tensor_mod.f90"): [tensor],
                                 os.path.join("src", "app", "fepx.f90"): [program]})

    def test_reset_deletes_counter_files_only(self):
        counters = self.touch("build", "a", "x.f90.gcda")
        notes = self.touch("build", "a", "x.f90.gcno")
        self.assertEqual(check_quick_coverage.reset_counters(os.path.join(self.root, "build")), 1)
        self.assertFalse(os.path.exists(counters))
        self.assertTrue(os.path.exists(notes))


if __name__ == "__main__":
    unittest.main()
