  !> Append a line.
  !>
  !> Arguments:
  !>   text  (in)  character  the line
  subroutine append(text)

    character(len=*), intent(in) :: text

    lines = [character(len=80) :: lines, text]

  end subroutine append

  !> Insert a line before line i.
  !>
  !> Arguments:
  !>   i     (in)  integer    line index
  !>   text  (in)  character  the line
  subroutine insert(i, text)

    integer, intent(in) :: i
    character(len=*), intent(in) :: text

    lines = [character(len=80) :: lines(1:i - 1), text, lines(i:)]

  end subroutine insert

  !> Replace line i.
  !>
  !> Arguments:
  !>   i     (in)  integer    line index
  !>   text  (in)  character  the new line
  subroutine replace(i, text)

    integer, intent(in) :: i
    character(len=*), intent(in) :: text

    lines(i) = text

  end subroutine replace

  !> Remove line i.
  !>
  !> Arguments:
  !>   i  (in)  integer  line index
  subroutine remove(i)

    integer, intent(in) :: i

    lines = [character(len=80) :: lines(1:i - 1), lines(i + 1:)]

  end subroutine remove

  !> Write the lines to case.cfg.
  !>
  !> Locals:
  !>   u, i  integer  unit, line index
  subroutine write_case()

    integer :: u, i

    open (newunit=u, file='case.cfg', status='replace', action='write')
    do i = 1, size(lines)
      write (u, '(a)') trim(lines(i))
    end do
    close (u)

  end subroutine write_case

