  !> Turn the base file's phase into a valid crystal-plasticity phase without hardening
  !> keywords (model, m, gammadot_0, tau_0 = 390 468 663; lines 5 and 20-22).
  subroutine cp_base()

    call replace(5, 'model crystal_plasticity')
    call append('m 0.01 0.01 0.01')
    call append('gammadot_0 1.0 1.0 1.0')
    call append('tau_0 390 468 663')

  end subroutine cp_base

  !> The crystal-plasticity base (cp_base) with saturation_anisotropic hardening and its
  !> parameters (lines 23-26).
  subroutine aniso_base()

    call cp_base()
    call append('hardening saturation_anisotropic')
    call append('h_0 100')
    call append('tau_s 700')
    call append('n 1')

  end subroutine aniso_base

  !> The crystal-plasticity base (cp_base) with kocks_mecking hardening and its parameters
  !> (Barton's, FEPX units; lines 23-30: hardening, km_b, km_h_n, km_rho_0, km_k1, km_k20,
  !> km_gammadot_k0, km_n).
  subroutine km_base()

    call cp_base()
    call append('hardening kocks_mecking')
    call append('km_b 2.48e-7')
    call append('km_h_n 0.125')
    call append('km_rho_0 2e7')
    call append('km_k1 4.5e5')
    call append('km_k20 14')
    call append('km_gammadot_k0 1e10')
    call append('km_n 100')

  end subroutine km_base

  !> A bcc crystal-plasticity phase with kocks_mecking hardening and irradiation on (Barton's
  !> parameters, FEPX units): the base with crystal_type bcc (c13, c33, c_over_a removed:
  !> lines 1-16), m, gammadot_0, tau_0 (17-19), the km_base lines (20-27), irradiation on and
  !> irr_h_d, irr_eta, irr_loop_density, irr_loop_diameter, irr_loop_normals (28-33).
  subroutine irr_base()

